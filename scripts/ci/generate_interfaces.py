#!/usr/bin/env python3
"""Render completion and CLI reference from the parser's public grammar."""
import argparse
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from mihomoctl import command_spec as spec


def flags(rows):
    return [name for name, _ in rows if name.startswith('--')]


def completion():
    commands = spec.public_commands()
    cases = []
    file_flags = set()
    value_flags = set()
    for command in commands:
        definition = spec.NATIVE.get(command, spec.BRIDGED.get(command))
        all_rows = []
        if isinstance(definition, dict):
            cases.append('    %s)\n      if ((COMP_CWORD == command_index+1)); then words=%r\n      else\n        case "$action" in' % (command, ' '.join(definition)))
            for action, rows in definition.items():
                rows = rows + ([spec.arg('--config')] if command in spec.BRIDGED else [])
                all_rows += rows
                cases.append('          %s) words=%r ;;' % (action, ' '.join(flags(rows) + ['--json','--help'])))
            cases.append('        esac\n      fi ;;')
        else:
            all_rows = list(definition)
            if command in spec.BRIDGED:
                all_rows += [spec.arg('--config')]
            if command == 'health-check':
                all_rows += spec.PROBE_OPTIONS
            words = flags(all_rows) + ['--json','--help']
            if command in ('exec','direct'): words += ['--']
            if command == 'health': words.insert(0, 'check')
            cases.append('    %s) words=%r ;;' % (command, ' '.join(words)))
        for flag, settings in all_rows:
            if flag.startswith('--') and settings.get('action') not in ('store_true','store_false'):
                if flag in ('--core','--config','--file','--output','--output-dir','--path','--wheelhouse','--python','--archive','--source-file','--url-file','--home-dir','--script'):
                    file_flags.add(flag)
                else:
                    value_flags.add(flag)
    return '''#!/usr/bin/env bash
# Generated by scripts/ci/generate_interfaces.py; edit mihomoctl/command_spec.py.
_mihomoctl_complete() {
  local current=${COMP_WORDS[COMP_CWORD]} previous=${COMP_WORDS[COMP_CWORD-1]}
  local command_index=1 index command action words=''
  COMPREPLY=()
  for ((index=1; index<COMP_CWORD; index++)); do
    [[ ${COMP_WORDS[index]} == -- ]] && return
  done
  while [[ ${COMP_WORDS[command_index]} == --user || ${COMP_WORDS[command_index]} == --system || ${COMP_WORDS[command_index]} == --json ]]; do
    ((command_index++))
  done
  if ((COMP_CWORD == command_index)); then
    mapfile -t COMPREPLY < <(compgen -W '%s --user --system --json --help' -- "$current")
    return
  fi
  command=${COMP_WORDS[command_index]}
  action=${COMP_WORDS[command_index+1]}
  case "$previous" in
    %s) mapfile -t COMPREPLY < <(compgen -f -- "$current"); return ;;
    %s) return ;;
  esac
  case "$command" in
%s
  esac
  mapfile -t COMPREPLY < <(compgen -W "$words" -- "$current")
}
complete -F _mihomoctl_complete mihomoctl
''' % (' '.join(commands), '|'.join(sorted(file_flags)), '|'.join(sorted(value_flags)), '\n'.join(cases))


def reference(language):
    introduction = ('# CLI reference\n\nGenerated grammar; use `mihomoctl COMMAND --help` before initialization.\n'
                    if language == 'en' else '# CLI 命令参考\n\n由实际解析定义生成；初始化前也可使用 `mihomoctl COMMAND --help`。\n')
    result = [introduction, '\n`mihomoctl [--user|--system] COMMAND [ARGS...] [--json]`\n\n',
              'Scope flags precede COMMAND. `exec` and `direct` pass everything after `--` to the child.\n\n',
              ('Shell operators outside `exec` remain in the caller. Wrap the entire installer shell; '
               'see [proxy inheritance and reviewed downloads](../first-run.md#install-a-third-party-cli-through-the-proxy).\n\n'
               if language == 'en' else
               '外层 Shell 运算符不属于 `exec` 的子进程；安装管道应包裹整个 Shell，见 '
               '[代理继承与下载审阅](../first-run.md#通过代理安装第三方-cli)。\n\n'),
              'Compatibility: `profiles` = `profile list`; `export --binding NAME` = `integration export NAME`; '
              '`dashboard` = `ui`; `health` = `health check`. Retired: `codex`, `paseo`, `opencode`, `diagnose`, `ready`.\n']
    for command in spec.public_commands():
        result += ['\n## ' + command + '\n\n```text\n', spec.command_parser(command).format_help(), '```\n']
        definition = spec.NATIVE.get(command, spec.BRIDGED.get(command))
        if isinstance(definition, dict):
            for action, rows in definition.items():
                rows = rows + ([spec.arg('--config')] if command in spec.BRIDGED else [])
                parser = spec.command_parser(command + ' ' + action, rows)
                result += ['\n### ' + command + ' ' + action + '\n\n```text\n', parser.format_help(), '```\n']
    return ''.join(result)


def outputs():
    return {'completions/mihomoctl.bash': completion(),
            **{'docs/' + lang + '/reference/cli.md': reference(lang) for lang in ('en','zh-CN')}}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for name, body in outputs().items():
        path = ROOT / name
        if args.check:
            if not path.is_file() or path.read_text(encoding='utf-8') != body:
                stale.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(body, encoding='utf-8', newline='\n')
    if stale:
        parser.error('stale-generated-interfaces: ' + ', '.join(stale))
    print('generated interfaces: current')


if __name__ == '__main__':
    main()
